# Build regex map keyed by phrase string, value = chinese.  Apply longest first.
_PHRASES_SORTED = sorted(_PHRASES, key=lambda p: -len(p[0]))

# Pre-compile regex for each phrase.  Use word boundaries when phrase starts/ends
# with an ASCII letter.  Otherwise plain replace.
def _compile_phrase(en):
    starts_word = en[0].isalnum()
    ends_word = en[-1].isalnum()
    pat = re.escape(en)
    pre = r"(?<![A-Za-z0-9_])" if starts_word else ""
    post = r"(?![A-Za-z0-9_])" if ends_word else ""
    return re.compile(pre + pat + post)

_COMPILED = [(_compile_phrase(en), cn) for en, cn in _PHRASES_SORTED]

# Color code regex (& or section sign followed by hex/k-o/r)
COLOR_RE = re.compile(r"(§[0-9a-fk-or]|&[0-9a-fk-or])", re.IGNORECASE)

# Hunter line pattern: "Hunter: <MobName> (<count>)"
HUNTER_RE = re.compile(r"^Hunter:\s+([A-Za-z][A-Za-z\s'\-]*?)\s*\((\d+)\)\s*$")

# Mod-internal item id pattern e.g. "create:experience_nugget"
ITEMID_RE = re.compile(r"^[a-z0-9_]+:[a-z0-9_]+$")

# Bullet list line e.g. "- Deeplands"
BULLET_RE = re.compile(r"^(\s*[-•✓]\s*)(.+)$")

_translate_cache = {}


def _translate_segment(text):
    """Translate a plain text segment (already stripped of color codes)."""
    if not text or not text.strip():
        return text

    s = text.strip()

    # Mod-internal ids: keep
    if ITEMID_RE.match(s):
        return text

    # Proper nouns kept as-is
    if s in PROPER_NOUNS_KEEP:
        return text

    # Hunter line
    m = HUNTER_RE.match(s)
    if m:
        prefix = text[: len(text) - len(text.lstrip())]
        suffix = text[len(text.rstrip()):]
        mob = m.group(1).strip()
        count = m.group(2)
        # Translate mob via phrase table
        cn_mob = mob
        for pat, cn in _COMPILED:
            if pat.fullmatch(mob):
                cn_mob = cn
                break
        if cn_mob == mob:
            # Try contained substitution
            new_mob = mob
            for pat, cn in _COMPILED:
                new_mob = pat.sub(cn, new_mob)
            cn_mob = new_mob
        return f"{prefix}猎人：{cn_mob} ({count}){suffix}"

    # Apply phrase substitution
    result = text
    for pat, cn in _COMPILED:
        result = pat.sub(cn, result)
    return result


def translate_value(val):
    """Translate one value preserving color codes and structure."""
    if not isinstance(val, str):
        return val
    if val == "":
        return val
    if val in _translate_cache:
        return _translate_cache[val]

    # Whole-line exact lookup first
    if val in EXACT_LINES:
        _translate_cache[val] = EXACT_LINES[val]
        return _translate_cache[val]

    # Split by color codes and translate text segments
    parts = COLOR_RE.split(val)
    out = []
    for p in parts:
        if not p:
            out.append(p)
        elif COLOR_RE.fullmatch(p):
            out.append(p)
        else:
            out.append(_translate_segment(p))
    result = "".join(out)
    _translate_cache[val] = result
    return result


def main():
    with IN_FILE.open("r", encoding="utf-8") as f:
        data = json.load(f)

    print(f"Loaded {len(data)} entries from {IN_FILE.name}")

    out = {}
    for k, v in data.items():
        if isinstance(v, list):
            out[k] = [translate_value(x) for x in v]
        else:
            out[k] = translate_value(v)

    OUT_FILE.parent.mkdir(parents=True, exist_ok=True)
    with OUT_FILE.open("w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=2)

    # Verify
    assert len(out) == len(data), f"Key count mismatch: {len(out)} vs {len(data)}"
    print(f"Wrote {len(out)} entries to {OUT_FILE}")
    print("OK: key count matches (5164 expected)")


if __name__ == "__main__":
    main()
