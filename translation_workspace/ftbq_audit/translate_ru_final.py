# Color code pattern: preserve &x and §x and {placeholders}
TOKEN_PATTERN = re.compile(r"(&[0-9a-fk-orA-FK-OR]|§[0-9a-fk-orA-FK-OR]|\{[^}]*\}|\[[^\]]*\]|<[^>]+>|https?://\S+|[a-zA-Z][a-zA-Z'-]*|[0-9]+|\s+|.)")

WORD_RE = re.compile(r"^[a-zA-Z][a-zA-Z'-]*$")


def apply_case(orig, translated):
    if not translated:
        return ""
    if orig.isupper() and len(orig) > 1:
        return translated.upper()
    if orig[0].isupper():
        return translated[0].upper() + translated[1:]
    return translated


# Latin -> Cyrillic transliteration map (fallback for unknown proper-noun-ish words)
TRANSLIT = {
    "shch": "щ", "sch": "щ", "sh": "ш", "ch": "ч", "kh": "х", "ts": "ц",
    "ya": "я", "yu": "ю", "yo": "ё", "zh": "ж", "ya": "я",
    "ph": "ф", "th": "т",
    "a": "а", "b": "б", "c": "к", "d": "д", "e": "е", "f": "ф", "g": "г",
    "h": "х", "i": "и", "j": "дж", "k": "к", "l": "л", "m": "м", "n": "н",
    "o": "о", "p": "п", "q": "к", "r": "р", "s": "с", "t": "т", "u": "у",
    "v": "в", "w": "в", "x": "кс", "y": "и", "z": "з",
}


def transliterate(w):
    """Latin -> Cyrillic transliteration. Preserves case roughly."""
    lw = w.lower()
    result = []
    i = 0
    while i < len(lw):
        # Try digraph
        matched = False
        for n in (4, 3, 2):
            if i + n <= len(lw):
                seg = lw[i:i + n]
                if seg in TRANSLIT:
                    result.append(TRANSLIT[seg])
                    i += n
                    matched = True
                    break
        if not matched:
            ch = lw[i]
            result.append(TRANSLIT.get(ch, ch))
            i += 1
    out = "".join(result)
    if w[0].isupper() and out:
        out = out[0].upper() + out[1:]
    return out


def translate_word(w):
    lw = w.lower()
    if lw in WORDS:
        return apply_case(w, WORDS[lw])
    # Fallback: transliterate unknown Latin word to Cyrillic
    return transliterate(w)


def translate_segment(text):
    """Translate a chunk of text (single line, no color stripping)."""
    if not text or not text.strip():
        return text
    # Check exact phrase match on stripped lowercased (after stripping color codes)
    stripped_colors = re.sub(r"&[0-9a-fk-orA-FK-OR]", "", text).strip()
    key = stripped_colors.lower().strip(" .,!?:;")
    if key in EXACT:
        # Preserve leading color codes
        m = re.match(r"^((?:&[0-9a-fk-orA-FK-OR])*)", text)
        prefix = m.group(1) if m else ""
        # Preserve trailing punctuation
        trail = ""
        for ch in reversed(text):
            if ch in ".,!?:;":
                trail = ch + trail
            else:
                break
        return prefix + EXACT[key] + trail

    # Token-by-token translation
    out = []
    for tok in TOKEN_PATTERN.findall(text):
        if WORD_RE.match(tok):
            out.append(translate_word(tok))
        else:
            out.append(tok)
    return "".join(out)


def translate_value(v):
    if isinstance(v, str):
        return translate_segment(v)
    if isinstance(v, list):
        return [translate_segment(x) if isinstance(x, str) else x for x in v]
    return v


