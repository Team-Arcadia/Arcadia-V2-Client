# Sort substitutions by length (longest first) so multi-word phrases match before
# their constituent words.
SUBSTITUTIONS = sorted(WORDS.items(), key=lambda kv: -len(kv[0]))

# Pre-compile regexes
SUB_PATTERNS = [
    (re.compile(r"(?<![A-Za-z])" + re.escape(en) + r"(?![A-Za-z])"), pt)
    for en, pt in SUBSTITUTIONS
]


def split_colors(text: str):
    """Yield (color_token_or_None, segment) for the input string.

    The color codes are preserved verbatim. The plain-text segments
    between codes are translated word-by-word.
    """
    out = []
    i = 0
    while i < len(text):
        m = COLOR_RE.match(text, i)
        if m:
            out.append((True, m.group(0)))
            i = m.end()
        else:
            j = i
            while j < len(text) and not COLOR_RE.match(text, j):
                j += 1
            out.append((False, text[i:j]))
            i = j
    return out


# Hunter: <Mob> (N) — translate prefix only, keep mob name + count untouched
HUNTER_RE = re.compile(r"^Hunter:\s*(.+?)\s*\((\d+)\)$")

# Color/format-only wrapper detection
WRAPPER_RE = re.compile(r"^((?:[&§][0-9a-fk-or])*)(.*?)((?:[&§][0-9a-fk-or])*)$", re.DOTALL)


def translate_plain(text: str) -> str:
    """Translate a single plain-text segment (no color codes inside)."""
    if not text.strip():
        return text
    stripped = text.strip()

    # Exact phrase match (try with and without trailing dot)
    if stripped in PHRASES:
        # Preserve leading/trailing whitespace
        return text.replace(stripped, PHRASES[stripped])
    if stripped.rstrip(".") in PHRASES:
        translated = PHRASES[stripped.rstrip(".")]
        if stripped.endswith("."):
            translated += "."
        return text.replace(stripped, translated)

    # Hunter: <Mob> (N) pattern
    m = HUNTER_RE.match(stripped)
    if m:
        mob = m.group(1)
        n = m.group(2)
        translated = f"Cacador: {mob} ({n})"
        return text.replace(stripped, translated)

    # Apply word-level substitutions (longest first)
    result = text
    for pat, pt in SUB_PATTERNS:
        result = pat.sub(pt, result)
    return result


def translate_entry(value: str) -> str:
    """Translate a full FTBQ value, preserving color codes."""
    if not value:
        return value

    # First: exact phrase lookup on the entire stripped value (incl. codes around).
    m = WRAPPER_RE.match(value)
    if m:
        prefix_codes, middle, suffix_codes = m.group(1), m.group(2), m.group(3)
        if middle in PHRASES:
            return prefix_codes + PHRASES[middle] + suffix_codes
        # Hunter pattern with codes wrapped around
        hm = HUNTER_RE.match(middle.strip())
        if hm:
            mob = hm.group(1)
            n = hm.group(2)
            return prefix_codes + f"Cacador: {mob} ({n})" + suffix_codes

    # Walk through, preserving color codes
    parts = split_colors(value)
    out = []
    for is_code, seg in parts:
        if is_code:
            out.append(seg)
        else:
            out.append(translate_plain(seg))
    translated = "".join(out)
    # Strip accents to match existing pt_br style
    return strip_accents(translated)


def main():
    with open(IN_FILE, "r", encoding="utf-8") as f:
        data = json.load(f)

    print(f"Loaded {len(data)} entries from input")

    out = {}
    for k, v in data.items():
        out[k] = translate_entry(v)

    OUT_FILE.parent.mkdir(parents=True, exist_ok=True)
    with open(OUT_FILE, "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=2, sort_keys=False)

    print(f"Wrote {len(out)} entries to {OUT_FILE}")
    # Quick stats
    unchanged = sum(1 for k in data if data[k] == out[k])
    print(f"Unchanged (kept EN): {unchanged}")
    print(f"Translated: {len(data) - unchanged}")


if __name__ == "__main__":
    main()
