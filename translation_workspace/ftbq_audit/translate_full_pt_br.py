    # Stats
    str_segments = 0
    changed = 0
    unchanged_examples = []
    for k, v in data.items():
        tv = out[k]
        if isinstance(v, list):
            for i, s in enumerate(v):
                str_segments += 1
                if s != tv[i]:
                    changed += 1
                elif s.strip() and any(c.isalpha() for c in s) and len(unchanged_examples) < 25:
                    unchanged_examples.append((k, s))
        else:
            str_segments += 1
            if v != tv:
                changed += 1
            elif v.strip() and any(c.isalpha() for c in v) and len(unchanged_examples) < 25:
                unchanged_examples.append((k, v))
    print(f"Total segments: {str_segments}, changed: {changed}")
