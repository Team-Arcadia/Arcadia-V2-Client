# Build extended phrase dict
ALL_PHRASES = dict(eng.PHRASES)
ALL_PHRASES.update(EXTRA_PHRASES)

# Build extended words list (will reuse engine's WORDS, add EXTRA_WORDS not already present)
ALL_WORDS = dict(eng.WORDS)
for k, v in EXTRA_WORDS.items():
    ALL_WORDS.setdefault(k, v)

# Sort by length descending
SORTED_SUBS = sorted(ALL_WORDS.items(), key=lambda kv: -len(kv[0]))
SUB_PATTERNS = [
    (re.compile(r"(?<![A-Za-zÀ-ÿ0-9_'])" + re.escape(en) + r"(?![A-Za-zÀ-ÿ0-9_'])"), pt)
    for en, pt in SORTED_SUBS
]

COLOR_RE = eng.COLOR_RE
WRAPPER_RE = eng.WRAPPER_RE
HUNTER_RE = eng.HUNTER_RE

# Mod ID literal pattern (e.g. create:powered_toggle_latch) - never translate
MOD_ID_RE = re.compile(r"^[a-z][a-z0-9_]*:[a-z0-9_/]+$")
# Tag pattern (e.g. #waystones:sharestones)
TAG_RE = re.compile(r"^#[a-z][a-z0-9_]*:[a-z0-9_/]+$")
# Command pattern
CMD_RE = re.compile(r"^/[a-zA-Z]+$")
# Tier weapon pattern: "T1 Melee", "T3 Pistols", etc.
TIER_RE = re.compile(r"^(T[1-4])\s+(\w[\w\s]*)$")


def translate_plain(text: str) -> str:
    if not text.strip():
        return text
    stripped = text.strip()

    # Exact phrase
    if stripped in ALL_PHRASES:
        return text.replace(stripped, ALL_PHRASES[stripped])
    if stripped.rstrip(".") in ALL_PHRASES:
        translated = ALL_PHRASES[stripped.rstrip(".")]
        if stripped.endswith("."):
            translated += "."
        return text.replace(stripped, translated)

    # Hunter: <Mob> (N)
    m = HUNTER_RE.match(stripped)
    if m:
        return text.replace(stripped, f"Cacador: {m.group(1)} ({m.group(2)})")

    # Word substitutions
    result = text
    for pat, pt in SUB_PATTERNS:
        result = pat.sub(pt, result)
    return result


def translate_string(value):
    if not isinstance(value, str) or not value:
        return value

    # Pass-through cases: mod IDs, tags, commands
    stripped = value.strip()
    if MOD_ID_RE.match(stripped) or TAG_RE.match(stripped) or CMD_RE.match(stripped):
        return value

    # Tier weapon: keep "T1/T2/...", translate suffix
    m = TIER_RE.match(stripped)
    if m:
        prefix, suffix = m.group(1), m.group(2)
        translated_suffix = translate_plain(suffix).strip()
        return strip_accents(value.replace(stripped, f"{prefix} {translated_suffix}"))

    # Whole-string phrase match with codes
    m = WRAPPER_RE.match(value)
    if m:
        prefix_codes, middle, suffix_codes = m.group(1), m.group(2), m.group(3)
        if middle in ALL_PHRASES:
            return strip_accents(prefix_codes + ALL_PHRASES[middle] + suffix_codes)
        hm = HUNTER_RE.match(middle.strip())
        if hm:
            return strip_accents(prefix_codes + f"Cacador: {hm.group(1)} ({hm.group(2)})" + suffix_codes)

    # Tokenize by color codes, translate plain segments
    parts = eng.split_colors(value)
    out = []
    for is_code, seg in parts:
        if is_code:
            out.append(seg)
        else:
            out.append(translate_plain(seg))
    return strip_accents("".join(out))


def translate_entry(value):
    if isinstance(value, list):
        return [translate_string(s) for s in value]
    return translate_string(value)


