def translate(value):
    if isinstance(value, list):
        return [translate(x) for x in value]
    if not isinstance(value, str):
        return value
    if value in EXACT:
        return EXACT[value]
    if value.strip() == "":
        return value
    out = value
    for pat, repl in PATTERNS:
        out = re.sub(pat, repl, out)
    # Clean up minor artifacts
    out = re.sub(r' {2,}', ' ', out)
    out = re.sub(r' ([,.;:!?])', r'\1', out)
    return out


def main():
    with open(INPUT, encoding='utf-8') as f:
        data = json.load(f)
    result = {k: translate(v) for k, v in data.items()}
    os.makedirs(os.path.dirname(OUTPUT), exist_ok=True)
    with open(OUTPUT, 'w', encoding='utf-8') as f:
        json.dump(result, f, ensure_ascii=False, indent=2)
    total = len(result)

    def has_cyr(v):
        if isinstance(v, str):
            return bool(re.search(r'[А-Яа-яЁё]', v))
        if isinstance(v, list):
            return any(isinstance(x, str) and re.search(r'[А-Яа-яЁё]', x) for x in v)
        return False

    translated = sum(1 for v in result.values() if has_cyr(v))
    print(f"keys={total}  with_cyrillic={translated}  coverage={translated/total:.1%}")


if __name__ == "__main__":
    main()
