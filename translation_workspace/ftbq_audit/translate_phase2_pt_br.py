# Sort by length descending (longest match first)
SUBSTITUTIONS = sorted(WORDS.items(), key=lambda kv: -len(kv[0]))

# Pre-compile patterns with word boundaries
SUB_PATTERNS = [
    (re.compile(r"(?<![A-Za-z0-9_'])" + re.escape(en) + r"(?![A-Za-z0-9_'])"), pt)
    for en, pt in SUBSTITUTIONS
]


def split_colors(text: str):
    """Split into (is_code, segment) preserving color codes."""
    out = []
    i = 0
    while i < len(text):
        m = COLOR_RE.match(text, i)
        if m:
            out.append((True, m.group(0)))
            i = m.end()
        else:
            j = i
            while j < len(text) and not COLOR_RE.match(text, j):
                j += 1
            out.append((False, text[i:j]))
            i = j
    return out


HUNTER_RE = re.compile(r"^Hunter:\s*(.+?)\s*\((\d+)\)$")
WRAPPER_RE = re.compile(r"^((?:[&§][0-9a-fk-or])*)(.*?)((?:[&§][0-9a-fk-or])*)$", re.DOTALL)


def translate_plain(text: str) -> str:
    """Translate a plain text segment (no color codes)."""
    if not text.strip():
        return text
    stripped = text.strip()

    # Exact phrase
    if stripped in PHRASES:
        return text.replace(stripped, PHRASES[stripped])
    if stripped.rstrip(".") in PHRASES:
        translated = PHRASES[stripped.rstrip(".")]
        if stripped.endswith("."):
            translated += "."
        return text.replace(stripped, translated)

    # Hunter: <Mob> (N) pattern
    m = HUNTER_RE.match(stripped)
    if m:
        mob = m.group(1)
        n = m.group(2)
        return text.replace(stripped, f"Cacador: {mob} ({n})")

    # Word substitutions
    result = text
    for pat, pt in SUB_PATTERNS:
        result = pat.sub(pt, result)
    return result


def translate_entry(value):
    """Translate a string or list-of-strings entry."""
    if isinstance(value, list):
        return [translate_string(s) for s in value]
    return translate_string(value)


def translate_string(value: str) -> str:
    if not isinstance(value, str) or not value:
        return value

    # Try whole-string phrase match (with codes wrapping the body)
    m = WRAPPER_RE.match(value)
    if m:
        prefix_codes, middle, suffix_codes = m.group(1), m.group(2), m.group(3)
        if middle in PHRASES:
            return strip_accents(prefix_codes + PHRASES[middle] + suffix_codes)
        hm = HUNTER_RE.match(middle.strip())
        if hm:
            mob = hm.group(1)
            n = hm.group(2)
            return strip_accents(prefix_codes + f"Cacador: {mob} ({n})" + suffix_codes)

    # Tokenize on color codes, translate each plain segment
    parts = split_colors(value)
    out = []
    for is_code, seg in parts:
        if is_code:
            out.append(seg)
        else:
            out.append(translate_plain(seg))
    translated = "".join(out)
    return strip_accents(translated)


