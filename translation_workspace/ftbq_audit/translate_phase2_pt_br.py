    with open(IN_FILE, "r", encoding="utf-8") as f:
        data = json.load(f)
    print(f"Loaded {len(data)} entries from input.")

    out = {}
    str_in = arr_in = 0
    for k, v in data.items():
        out[k] = translate_entry(v)
        if isinstance(v, list):
            arr_in += 1
        else:
            str_in += 1

    OUT_FILE.parent.mkdir(parents=True, exist_ok=True)
    with open(OUT_FILE, "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=2, sort_keys=False)

    print(f"Wrote {len(out)} entries to {OUT_FILE}")
    print(f"Inputs - strings: {str_in}, arrays: {arr_in}")

    # Quick verification stats
    same_strings = 0
    changed_strings = 0
    total_str_segments = 0
    for k, v in data.items():
        tv = out[k]
        if isinstance(v, list):
            for i, s in enumerate(v):
                total_str_segments += 1
                if s == tv[i]:
                    same_strings += 1
                else:
                    changed_strings += 1
        else:
            total_str_segments += 1
            if v == tv:
                same_strings += 1
            else:
                changed_strings += 1
    print(f"Total string segments: {total_str_segments}")
    print(f"Changed: {changed_strings}, Unchanged (kept EN/empty): {same_strings}")


