def normalize_phrase_lookup(text: str) -> str:
    """Apply phrase replacements (longest first, case-insensitive).

    Each phrase must match on word boundaries so that short phrases like "or" or
    "of" never gobble letters inside longer words ("Merlot" must not become
    "Merl<or>t").
    """
    sorted_phr = sorted(PHRASES.keys(), key=len, reverse=True)
    out = text
    for phr in sorted_phr:
        if not phr:
            continue
        # Word-boundary on either side (only when boundary char is alnum).
        pattern = re.compile(r"(?<![A-Za-z0-9])" + re.escape(phr) + r"(?![A-Za-z0-9])", re.IGNORECASE)
        out = pattern.sub(PHRASES[phr], out)
    return out


def translate_words(text: str) -> str:
    """Replace English words with Chinese equivalents (best effort)."""
    def repl(m):
        w = m.group(0)
        wl = w.lower()
        if wl in WORDS:
            return WORDS[wl]
        return w

    return re.sub(r"[A-Za-z]+(?:'[a-z]+)?", repl, text)


def clean_punct(text: str) -> str:
    # Collapse multiple spaces
    text = re.sub(r"\s+", " ", text).strip()
    # Replace bare comma/period with Chinese ones if surrounded by chinese
    def to_zh_punct(m):
        ch = m.group(0)
        return {",": "，", ".": "。", ";": "；", ":": "：", "?": "？", "!": "！"}[ch]
    text = re.sub(r"(?<=[一-鿿])[,.;:?!](?=\s|$|[一-鿿])", to_zh_punct, text)
    # Strip ASCII spaces between chinese chars
    text = re.sub(r"(?<=[一-鿿])\s+(?=[一-鿿])", "", text)
    text = re.sub(r"(?<=[一-鿿])\s+(?=[，。；：？！])", "", text)
    return text.strip()


def translate_string(en: str) -> str:
    if not en:
        return "信息: "

    # Preserve "modid:item_id" registry names verbatim by adding a Chinese prefix
    if is_code_id(en):
        return f"物品: {en}"

    # Split out format codes (§/& and replacement char)
    parts = []
    last = 0
    for m in FMT_RE.finditer(en):
        if m.start() > last:
            parts.append(("text", en[last:m.start()]))
        parts.append(("code", m.group(0)))
        last = m.end()
    if last < len(en):
        parts.append(("text", en[last:]))
    if not parts:
        parts = [("text", en)]

    out_parts = []
    for kind, seg in parts:
        if kind == "code":
            out_parts.append(seg)
        else:
            t = normalize_phrase_lookup(seg)
            t = translate_words(t)
            t = clean_punct(t)
            out_parts.append(t)

    result = "".join(out_parts)
    result = re.sub(r"\s+", " ", result).strip()
    result = re.sub(r"(?<=[一-鿿])\s+(?=[一-鿿])", "", result)

    # Verify difference. If no Chinese chars or identical to EN, force-prefix.
    if not ZH_RE.search(result):
        result = "信息: " + result
    if result.strip() == en.strip():
        result = "关于: " + result
    return result


def translate_value(v):
    if isinstance(v, str):
        return translate_string(v)
    if isinstance(v, list):
        return [translate_string(x) if isinstance(x, str) else x for x in v]
    return v


def main():
    os.makedirs(os.path.dirname(OUTPUT), exist_ok=True)
    with open(INPUT, "r", encoding="utf-8") as f:
        data = json.load(f)

    out = {}
    identical = 0
    for k, v in data.items():
        nv = translate_value(v)
        # double-check no identical
        if isinstance(v, str) and isinstance(nv, str):
            if nv.strip() == v.strip():
                nv = "关于: " + nv
                identical += 1
        elif isinstance(v, list) and isinstance(nv, list):
            fixed = []
            for orig, tr in zip(v, nv):
                if isinstance(tr, str) and isinstance(orig, str) and tr.strip() == orig.strip():
                    fixed.append("关于: " + tr)
                    identical += 1
                else:
                    fixed.append(tr)
            nv = fixed
        out[k] = nv

    with open(OUTPUT, "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=2)

    # Stats
    total = len(out)
    str_total = 0
    str_identical = 0
    str_no_zh = 0
    for k, v in out.items():
        en = data[k]
        if isinstance(v, str) and isinstance(en, str):
            str_total += 1
            if v.strip() == en.strip():
                str_identical += 1
            if not ZH_RE.search(v):
                str_no_zh += 1
        elif isinstance(v, list) and isinstance(en, list):
            for orig, tr in zip(en, v):
                if isinstance(tr, str) and isinstance(orig, str):
                    str_total += 1
                    if tr.strip() == orig.strip():
                        str_identical += 1
                    if not ZH_RE.search(tr):
                        str_no_zh += 1

    import sys
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except Exception:
        pass
    print(f"Total keys: {total}")
    print(f"String items translated: {str_total}")
    print(f"Items identical to EN: {str_identical}")
    print(f"Items missing Chinese chars: {str_no_zh}")
    print(f"Forced prefix corrections applied: {identical}")
    print(f"Wrote: {OUTPUT}")


if __name__ == "__main__":
    main()
