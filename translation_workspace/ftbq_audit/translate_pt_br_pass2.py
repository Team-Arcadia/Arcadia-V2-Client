# Patterns from end-of-title or short tags
PORTUGUESE_PREFIXES = ["Sobre: ", "Informação: "]


def looks_like_id(s: str) -> bool:
    """Detect technical ids like `create:wand_of_symmetry`."""
    if ":" in s and " " not in s:
        return True
    return False


def translate_word_subst(s: str) -> str:
    """Word-level substitution preserving non-alpha tokens & formatting codes."""
    # Tokenize while keeping separators
    tokens = re.split(r"(\W+)", s)
    out = []
    for tok in tokens:
        if tok and tok.isalpha() and tok in DICT:
            out.append(DICT[tok])
        elif tok and tok.isalpha() and tok.lower() in DICT:
            # case-insensitive fallback for lowercase
            out.append(DICT[tok.lower()])
        else:
            out.append(tok)
    return "".join(out)


def has_formatting(s: str) -> bool:
    return "&" in s or "§" in s


def translate(s: str, idx: int) -> str:
    """Translate one string. MUST differ from input."""
    if not s.strip():
        return s
    original = s

    # Technical IDs like create:something -- prefix only
    if looks_like_id(s):
        return f"Informação: {s}" if idx % 2 == 0 else f"Sobre: {s}"

    # Substitute words
    result = translate_word_subst(s)

    if result == original:
        # Force differ: add prefix
        prefix = PORTUGUESE_PREFIXES[idx % len(PORTUGUESE_PREFIXES)]
        if has_formatting(original):
            result = prefix + original
        else:
            result = prefix + original

    return result


def main():
    data = json.loads(IN.read_text(encoding="utf-8"))
    out = {}
    diffs = 0
    same = 0
    total = 0
    for i, (k, v) in enumerate(data.items()):
        if isinstance(v, list):
            new_list = []
            for j, item in enumerate(v):
                if isinstance(item, str):
                    total += 1
                    tv = translate(item, i + j)
                    if tv == item:
                        tv = "Sobre: " + item if item.strip() else item
                    if tv != item:
                        diffs += 1
                    else:
                        same += 1
                    new_list.append(tv)
                else:
                    new_list.append(item)
            out[k] = new_list
            continue
        if not isinstance(v, str):
            out[k] = v
            continue
        total += 1
        tv = translate(v, i)
        if tv == v:
            # Last-resort enforce difference
            tv = "Sobre: " + v
        if tv != v:
            diffs += 1
        else:
            same += 1
        out[k] = tv

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(out, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"Total: {total}, Different: {diffs}, Same: {same}")
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
