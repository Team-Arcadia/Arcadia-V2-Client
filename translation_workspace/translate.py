def translate_weapon_config(en):
    # Patterns: '<Type> damage modifier' or '<Type> attack speed'
    m = re.match(r'^(.+?) damage modifier$', en)
    if m:
        name = m.group(1)
        if name in WEAPON_KEYS_FR:
            return f"Modificateur de dégâts {WEAPON_KEYS_FR[name]}"
        if name in MATERIAL_KEYS_FR:
            return f"Modificateur de dégâts de base {MATERIAL_KEYS_FR[name]}"
    m = re.match(r'^(.+?) base damage modifier$', en)
    if m:
        name = m.group(1)
        if name in MATERIAL_KEYS_FR:
            return f"Modificateur de dégâts de base {MATERIAL_KEYS_FR[name]}"
    m = re.match(r'^(.+?) attack speed$', en)
    if m:
        name = m.group(1)
        if name in WEAPON_KEYS_FR:
            return f"Vitesse d'attaque {WEAPON_KEYS_FR[name]}"
    return None


def translate_simply(en, key=None):
    """Translate a simplyswords value."""
    # Direct fixed lookup
    if en in SIMPLY_FIXED:
        return SIMPLY_FIXED[en]
    # Effect names (top-level keys effect.simplyswords.X)
    if en in EFFECTS:
        return EFFECTS[en]
    # Unique sword names
    if en in UNIQUE_SWORDS:
        return UNIQUE_SWORDS[en]
    # Material × type
    r = translate_material_weapon(en)
    if r is not None:
        return r
    # §6Name§7 ... patterns
    r = translate_unique_modifier(en)
    if r is not None:
        return r
    # Weapon/material config keys
    r = translate_weapon_config(en)
    if r is not None:
        return r
    # Fall through: keep English
    return en


