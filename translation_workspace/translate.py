def translate_material_weapon(en):
    """Translate '<Material> <WeaponType>' patterns."""
    # Sort materials by length descending so longer ones (e.g. "End Gobber", "Star Platinum") match first
    for mat_en, mat_fr in sorted(MATERIALS.items(), key=lambda x: -len(x[0])):
        if en.startswith(mat_en + " "):
            rest = en[len(mat_en)+1:]
            if rest in WEAPON_TYPES:
                return f"{WEAPON_TYPES[rest]} {mat_fr}"
    return None

