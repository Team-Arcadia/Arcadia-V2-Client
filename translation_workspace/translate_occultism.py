def translate_ritual_message(value):
    # Patterns: "Ritual completed successfully: X.", "Interruption in the ritual: X.", "Starting the ritual: X."
    m = re.match(r"^Ritual completed successfully: (.+?)\.$", value)
    if m:
        return f"Rituel terminé avec succès : {translate_ritual_action(m.group(1))}."
    m = re.match(r"^Interruption in the ritual: (.+?)\.$", value)
    if m:
        return f"Interruption du rituel : {translate_ritual_action(m.group(1))}."
    m = re.match(r"^Starting the ritual: (.+?)\.$", value)
    if m:
        return f"Démarrage du rituel : {translate_ritual_action(m.group(1))}."
    return None

