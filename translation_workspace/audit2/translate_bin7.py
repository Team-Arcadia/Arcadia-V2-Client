    in_path = MISSING_DIR / f"{mod}.json"
    fr_path = JAR_FR_DIR / f"{mod}.json"
    out_path = OUT_DIR / f"{mod}.json"
    if not in_path.exists():
        fail_mods.append((mod, "no input"))
        continue
    missing = load_json_safe(in_path)
    fr_jar = load_json_safe(fr_path)
    out = {}
    for k, v in missing.items():
        # 1) check if key already exists in fr_jar
        if k in fr_jar:
            out[k] = fr_jar[k]
            continue
        # 2) glossary
        if isinstance(v, str):
            g = translate_via_glossary(v)
            if g is not None:
                out[k] = g
                continue
            # 3) leave for manual + word-substitute fallback (not perfect but better than English)
            out[k] = fallback_word_substitute(v)
        else:
            out[k] = v
    write_json(out_path, out)
    processed += 1
    total_keys += len(out)

