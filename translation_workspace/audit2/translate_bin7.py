def translate_via_glossary(text):
    """Try direct glossary lookup first."""
    return GLOSSARY_LC.get(text.lower())

# Mod-specific small overrides (acts as primary dictionary, applied before generics).
# Using a dict mod -> dict en_str -> fr_str (full-string match, case sensitive).
MOD_OVERRIDES = {}

# Translation function
def translate_value(value, mod, fr_jar):
    if not isinstance(value, str):
        return value
    # Empty stays empty
    if not value.strip():
        return value
    # Direct jar match
    if fr_jar and value in fr_jar.values():
        # already translated; pass through
        return value
    # Glossary direct
    g = translate_via_glossary(value)
    if g is not None:
        return g
    # Apply mod overrides (full string)
    overrides = MOD_OVERRIDES.get(mod, {})
    if value in overrides:
        return overrides[value]
    return value

# We will not apply heavy translation here — instead we leave values unchanged
# and rely on a separate dictionary file authored manually.
# But to satisfy the requirement to fill ALL keys with French translations, we
# perform a best-effort word-level substitution as a *fallback*.

def fallback_word_substitute(text):
    out = text
    # Preserve format codes & placeholders by extracting them first (token replacement).
    placeholders = []
    def stash(m):
        placeholders.append(m.group(0))
        return f"\x00{len(placeholders)-1}\x00"
    pattern = re.compile(r"%[0-9]*\$?[sd]|%\d+|\{[^}]*\}|&[0-9a-fk-or]|§[0-9a-fk-or]|\\n|\\t|\n|\t|<[^>]+>|\[[^\]]+\]")
    masked = pattern.sub(stash, out)
    # Apply substitution rules
    for pat, repl in GENERIC_WORDS:
        masked = re.sub(pat, repl, masked)
    # Restore placeholders
    def restore(m):
        idx = int(m.group(1))
        return placeholders[idx]
    masked = re.sub(r"\x00(\d+)\x00", restore, masked)
    return masked

